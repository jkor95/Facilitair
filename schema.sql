create extension if not exists pgcrypto;

create table if not exists public.dm_accounts (
  id uuid primary key default gen_random_uuid(),
  name text not null,
  username text not null,
  username_key text not null unique,
  email text not null default '',
  role text not null check (role in ('admin','facility','staff')),
  active boolean not null default true,
  password_hash text not null,
  password_salt text not null,
  password_cipher text not null,
  password_iv text not null,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.dm_sessions (
  id uuid primary key default gen_random_uuid(),
  account_id uuid not null references public.dm_accounts(id) on delete cascade,
  token_hash text not null unique,
  created_at timestamptz not null default now(),
  expires_at timestamptz not null
);

create table if not exists public.dm_tickets (
  id bigint generated by default as identity primary key,
  ticket_no text unique,
  reporter text not null,
  location text not null,
  category text not null,
  urgency text not null check (urgency in ('laag','normaal','hoog','spoed')),
  title text not null,
  description text not null,
  can_continue text not null default 'ja',
  photo_path text,
  status text not null default 'open' check (status in ('open','progress','wait','done')),
  assignee uuid references public.dm_accounts(id) on delete set null,
  internal_note text not null default '',
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.dm_ticket_history (
  id uuid primary key default gen_random_uuid(),
  ticket_id bigint not null references public.dm_tickets(id) on delete cascade,
  at timestamptz not null default now(),
  actor text not null,
  actor_id uuid,
  action text not null
);

create table if not exists public.dm_routing (
  category text primary key,
  account_id uuid references public.dm_accounts(id) on delete set null,
  assign_all boolean not null default false,
  updated_at timestamptz not null default now()
);

create table if not exists public.dm_routing_members (
  category text not null references public.dm_routing(category) on delete cascade,
  account_id uuid not null references public.dm_accounts(id) on delete cascade,
  primary key(category,account_id)
);

create table if not exists public.dm_ticket_assignments (
  ticket_id bigint not null references public.dm_tickets(id) on delete cascade,
  account_id uuid not null references public.dm_accounts(id) on delete cascade,
  primary key(ticket_id,account_id)
);

create table if not exists public.dm_ticket_counters (
  ticket_date date primary key,
  last_number integer not null default 0 check (last_number >= 0),
  updated_at timestamptz not null default now()
);

create or replace function public.dm_next_ticket_number()
returns jsonb
language plpgsql
security invoker
set search_path = public
as $$
declare
  v_date date := (now() at time zone 'Europe/Amsterdam')::date;
  v_number integer;
begin
  insert into public.dm_ticket_counters(ticket_date,last_number,updated_at)
  values (v_date,1,now())
  on conflict (ticket_date) do update
    set last_number = public.dm_ticket_counters.last_number + 1, updated_at = now()
  returning last_number into v_number;
  if v_number > 999 then raise exception 'Maximaal 999 tickets per dag bereikt'; end if;
  return jsonb_build_object('ticket_date',to_char(v_date,'YYYY-MM-DD'),'number',v_number);
end;
$$;

create table if not exists public.dm_settings (
  key text primary key,
  value jsonb not null,
  updated_at timestamptz not null default now()
);

create table if not exists public.dm_audit_logs (
  id uuid primary key default gen_random_uuid(),
  at timestamptz not null default now(),
  actor text not null,
  actor_id uuid,
  type text not null,
  target_id text not null default '',
  action text not null
);

create table if not exists public.dm_invites (
  id uuid primary key default gen_random_uuid(),
  account_id uuid not null references public.dm_accounts(id) on delete cascade,
